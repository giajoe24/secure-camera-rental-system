# --------------------------------------------------
# 電磁ロック(GPIO)
# --------------------------------------------------

# 電磁ロックのリレー(または MOSFET)につながる GPIO 番号(BCM番号)
# ※ ピン番号(物理ピン 12 番など)ではなく、GPIO 番号です。
