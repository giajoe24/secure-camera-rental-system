# nfcpy に渡すデバイス指定
# "usb" ならUSB接続の最初に見つかったリーダーを使います。
# RC-S380 を明示する場合は "usb:054c:06c3"(RC-S380/P)や
# "usb:054c:06c1"(RC-S380/S)のように書けます。
CARD_READER_DEVICE = "usb"

# 読み取る対象のカード種別
#   "212F" : FeliCa(212kbps)
#   "424F" : FeliCa(424kbps)
#   "106A" : NFC Type A(MIFARE など)
#   "106B" : NFC Type B
# 社員証の種類が分かっている場合は、それだけに絞ると読み取りが安定します。
